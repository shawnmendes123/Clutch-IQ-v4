"""Generates WALKTHROUGH.md from the narration in tools/record_walkthrough.js,
so the written guide and the recorded video always say the same thing.

    python tools/build_walkthrough_doc.py
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "tools" / "record_walkthrough.js"

TITLES = {
    0: "Opening",
    1: "The shell: rail, engine badge, backend settings, Viva mode",
    2: "Mission control",
    3: "Operations · Data & upload",
    4: "Operations · Live queue & matchmaking",
    5: "Operations · Tournament",
    6: "Operations · Burnout & coach",
    7: "Control room · Live session (Unit 1)",
    8: "Control room · Q-learning and the TD update",
    9: "Control room · MDP explorer (Unit 3)",
    10: "Control room · Dynamic programming (Unit 4)",
    11: "RL lab · Bandit arena (Unit 2)",
    12: "RL lab · Monte Carlo lab (Unit 5)",
    13: "RL lab · Algorithm comparison",
    14: "Academic section",
    15: "Viva mode, and the offline engine",
    16: "Closing cards",
}


def clean(s: str) -> str:
    s = s.replace("\\'", "'").replace('\\"', '"')
    s = re.sub(r"<b>(.*?)</b>", r"**\1**", s)
    s = re.sub(r"<i>(.*?)</i>", r"*\1*", s)
    s = re.sub(r"<sub>(.*?)</sub>", r"\1", s)
    s = re.sub(r"<span>(.*?)</span>", r"\1", s)
    s = re.sub(r"&nbsp;|&rarr;", " ", s)
    s = re.sub(r"<[^>]+>", "", s)
    return re.sub(r"\s+", " ", s).strip()


def main() -> None:
    src = SRC.read_text()
    chapters = re.split(r"\nCH\[(\d+)\] = async \(\) => \{", src)
    out = [
        "# Clutch IQ v4 — screen-by-screen walkthrough",
        "",
        "The narration from the recorded walkthrough, in order, so you can read it or",
        "use it as a script. Generated by `tools/build_walkthrough_doc.py` from",
        "`tools/record_walkthrough.js` — the video and this file cannot drift apart.",
        "",
    ]
    for i in range(1, len(chapters), 2):
        n, body = int(chapters[i]), chapters[i + 1].split("\n};")[0]
        out += [f"## {n}. {TITLES.get(n, 'Chapter ' + str(n))}", ""]
        for m in re.finditer(
            r"(await (?:say|read|card|go|click|hover|set)\()(.*?)(?=\n  await |\n\};|\Z)",
            body, re.S,
        ):
            call, args = m.group(1), m.group(2)
            quoted = re.findall(r"'((?:[^'\\]|\\.)*)'", args)
            if not quoted:
                continue
            if "card(" in call:
                text = " — ".join(clean(q) for q in quoted[:2] if clean(q))
                bullets = [clean(q) for q in quoted[2:] if clean(q) and len(q) > 12]
                if text:
                    out.append(f"**{text}**")
                out += [f"- {b}" for b in bullets] + [""]
                continue
            # the narration is the last string argument that reads like a sentence
            cands = [clean(q) for q in quoted if len(clean(q)) > 25]
            if not cands:
                continue
            out.append(cands[-1])
            out.append("")
    txt = "\n".join(out).replace("\n\n\n", "\n\n")
    (ROOT / "WALKTHROUGH.md").write_text(txt)
    print("WALKTHROUGH.md", len(txt.split()), "words")


if __name__ == "__main__":
    main()
