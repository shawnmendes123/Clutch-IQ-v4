"""Builds assets/static_data.js — the data the browser engine needs offline.

Everything here is generated from the Python sources of truth (production
Q-table, sample maps, syllabus matrix, formal spec), so the offline UI can
never drift from the backend. Run after retraining:  python tools/build_static.py
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

import pandas as pd  # noqa: E402

import rl_core as core  # noqa: E402
import syllabus  # noqa: E402
from tournament_builder import load_maps_csv  # noqa: E402


def main():
    with open(os.path.join(ROOT, "q_table.json")) as f:
        q_table = json.load(f)
    with open(os.path.join(ROOT, "q_table_meta.json")) as f:
        q_meta = json.load(f)
    maps = load_maps_csv(pd.read_csv(os.path.join(ROOT, "sample_maps.csv")))
    exp_path = os.path.join(ROOT, "experiments", "results.json")
    experiments = None
    if os.path.exists(exp_path):
        with open(exp_path) as f:
            experiments = json.load(f)
    data = {"version": "4.0", "q_table": q_table, "q_meta": q_meta, "sample_maps": maps,
            "coverage": syllabus.coverage(), "spec": core.spec(), "experiments": experiments}
    out = os.path.join(ROOT, "assets", "static_data.js")
    with open(out, "w", encoding="utf-8") as f:
        f.write("/* AUTO-GENERATED by tools/build_static.py — do not edit by hand. */\n")
        f.write("(function(root){ root.CLUTCH_STATIC = ")
        json.dump(data, f, separators=(",", ":"), ensure_ascii=False)
        f.write("; })(typeof window !== 'undefined' ? window : globalThis);\n")
    print(f"wrote {out} ({os.path.getsize(out) // 1024} KB)")


if __name__ == "__main__":
    main()
